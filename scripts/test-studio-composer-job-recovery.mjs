/** What reaches a service or leaves the page: every request but a GET, a session create, an upload, a navigation (storage is checked apart). */
const serverActions = log => log.filter(entry => entry[0] === 'fetch' ? entry[1] !== 'GET' : ['createSession', 'uploadFileToResearcher', 'assign'].includes(entry[0]))
/** The requests an action makes, from its session create to its POST, with the fresh session id and new job id normalised. */
function actionPayload(log) {
  const start = log.findIndex(entry => entry[0] === 'createSession')
  const end = log.findIndex((entry, i) => i > start && entry[0] === 'fetch' && entry[1] === 'POST')
  assert.ok(start >= 0 && end > start, 'an action ran')
  const session = log[start][1]
  return JSON.parse(JSON.stringify(log.slice(start, end + 1)).replaceAll(session, '<session>'))
}
