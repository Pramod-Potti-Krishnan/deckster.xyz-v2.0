    ui.render({ open: false }); await ui.settle(2); ui.render({ open: true }); await ui.settle()
    deq(ui.log.slice(mark + 1).filter(entry => entry[2]?.includes('/jobs/')), [], 'nothing left to resume')
    await ui.close()
    // A record that names a newer job is not removed by an old notice's Dismiss.
    const stale = on({ stored: { [KEY]: record(ORPHAN_USE, OLD_SESSION, 'use') }, jobs: orphanUse() })
    await stale.settle()
    stale.store.set(KEY, record(NEW_JOB, 'fresh', 'use'))
